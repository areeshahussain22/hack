// Build step: turns every policy item into a meaning vector with Gemini embeddings (about 3 API calls).
// Output: lib/policy-embeddings.js. If the key is missing or the API fails, it writes an empty file
// and the app falls back to keyword search. It never breaks the build.
import fs from 'node:fs';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'lib', 'policy-embeddings.js');
const MODEL = process.env.GEMINI_EMBED_MODEL || 'gemini-embedding-001';
const DIMS = 256;      // small vectors: fast and light, good enough for 270 short items
const BATCH = 100;     // max texts per batch request
const sleep = ms => new Promise(r => setTimeout(r, ms));

function write(data) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, '// AUTO-GENERATED by scripts/build-embeddings.mjs. Do not edit.\nexport default ' + JSON.stringify(data) + ';\n');
}
const empty = reason => { console.warn(`[embeddings] skipped: ${reason}. Keyword search only.`); write({ model: null, dims: 0, vectors: {} }); };

function normalize(v) {
  const n = Math.sqrt(v.reduce((a, x) => a + x * x, 0)) || 1;
  return v.map(x => +(x / n).toFixed(4));
}

async function embedBatch(key, texts) {
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:batchEmbedContents`, {
      method: 'POST',
      headers: { 'x-goog-api-key': key, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        requests: texts.map(text => ({
          model: `models/${MODEL}`, content: { parts: [{ text }] },
          taskType: 'RETRIEVAL_DOCUMENT', outputDimensionality: DIMS,
        })),
      }),
    });
    if (res.ok) return (await res.json()).embeddings.map(e => normalize(e.values));
    if (res.status === 429 || res.status >= 500) { await sleep(2000 * 2 ** attempt); continue; }
    throw new Error(`HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`);
  }
  throw new Error('too many retries');
}

const key = process.env.GEMINI_API_KEY;
if (!key) empty('GEMINI_API_KEY not set');
else {
  try {
    const { default: INDEX } = await import(path.join(process.cwd(), 'lib', 'policy-index.js'));
    const items = INDEX.items;
    const vectors = {};
    for (let i = 0; i < items.length; i += BATCH) {
      const chunk = items.slice(i, i + BATCH);
      const texts = chunk.map(it => `${INDEX.files[it.fileNo].title} - ${it.heading}\n${it.text}`.slice(0, 2000));
      const embs = await embedBatch(key, texts);
      chunk.forEach((it, k) => { vectors[it.id] = embs[k]; });
    }
    write({ model: MODEL, dims: DIMS, vectors });
    console.log(`[embeddings] embedded ${Object.keys(vectors).length} items with ${MODEL} (${DIMS} dims)`);
  } catch (e) {
    empty(e.message);
  }
}
