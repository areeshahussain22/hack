// Parses every policy file into "items" (the citation unit, e.g. 01_returns_policy.md §2.1).
// Also reads front matter (effective_date, scope) and cross-references [file NN, Section X].
// Output: lib/policy-index.js (a JS module, so it is bundled on Vercel and in Docker).
import fs from 'node:fs';
import path from 'node:path';

const DIR = path.join(process.cwd(), 'policies');
const OUT = path.join(process.cwd(), 'lib', 'policy-index.js');

// Safety: drop any line written as an instruction to an AI/assistant.
// Policy text is data, never commands for our bot.
const INJECTION = /(ignore (all )?(previous|prior|above) instructions|system (override|prompt)|(instructions?|notes?) for [\w\s-]*(assistants?|ai|bots?)\b|\b(chat|customer[- ]service|support) ?bots?\b|you are (an?|the) (ai|assistant|bot)|as an ai)/i;

function parseFrontMatter(raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  const meta = {};
  if (m) for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m ? raw.slice(m[0].length) : raw };
}

function parseRefs(text) {
  const refs = [];
  for (const m of text.matchAll(/\[file (\d{2})(?:,\s*Section\s*([\d.]+))?\]/gi)) refs.push({ fileNo: m[1], section: m[2] || null });
  return refs;
}

function parseFile(file, raw, dropped) {
  const { meta, body } = parseFrontMatter(raw.replace(/\r\n/g, '\n'));
  const fileNo = file.slice(0, 2);
  const items = [];
  let heading = '';
  let sectionNo = '';
  let cur = null;
  const push = () => {
    if (cur && cur.lines.join('').trim()) {
      const text = cur.lines.join('\n').trim();
      // The policy files label worked examples "(illustration only)": their numbers show a method, not a rule.
      const example = /illustration only/i.test(`${cur.heading} ${text}`);
      items.push({ id: `${fileNo}:${cur.item}`, fileNo, file, item: cur.item, heading: cur.heading, text, refs: parseRefs(text), example });
    }
    cur = null;
  };
  for (const line of body.split('\n')) {
    if (INJECTION.test(line)) { dropped.push(`${file}: ${line.trim().slice(0, 80)}`); continue; }
    const h2 = line.match(/^##\s+(\d+)\.\s*(.+)$/);
    if (h2) { push(); sectionNo = h2[1]; heading = `${h2[1]}. ${h2[2].trim()}`; continue; }
    if (/^#\s/.test(line)) continue; // file title
    const it = line.match(/^\*\*(\d+(?:\.\d+)*)\*\*\s*(.*)$/);
    if (it) { push(); cur = { item: it[1], heading, lines: [it[2]] }; continue; }
    if (cur) cur.lines.push(line);
    else if (line.trim() && sectionNo) cur = { item: sectionNo, heading, lines: [line] }; // text before first item
  }
  push();
  return {
    meta: {
      file, fileNo, doc_id: meta.doc_id, title: meta.title, version: meta.version,
      effective_date: meta.effective_date, scope: (meta.scope || 'general').toLowerCase(),
    },
    items,
  };
}

const files = fs.readdirSync(DIR).filter(f => /^\d{2}_.+\.md$/i.test(f)).sort();
const dropped = [];
const parsed = files.map(f => parseFile(f, fs.readFileSync(path.join(DIR, f), 'utf8'), dropped));
const index = {
  files: Object.fromEntries(parsed.map(p => [p.meta.fileNo, p.meta])),
  items: parsed.flatMap(p => p.items),
};
fs.mkdirSync(path.dirname(OUT), { recursive: true }); // lib/ may not exist yet on a fresh clone
fs.writeFileSync(OUT,'// AUTO-GENERATED by scripts/build-index.mjs. Do not edit.\nexport default ' + JSON.stringify(index) + ';\n');
console.log(`Indexed ${index.items.length} items from ${files.length} files. Dropped ${dropped.length} unsafe line(s).`);
dropped.forEach(d => console.log('  dropped ->', d));
